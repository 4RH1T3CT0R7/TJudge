#!/usr/bin/env ruby
# Дилемма заключённого: стратегия «око за око» (tit for tat).
# Первый ход - сотрудничество, дальше повтор прошлого хода соперника.
# Протокол: ← строка от судьи (stdin), → ваша строка (stdout).
# Отладку печатайте через warn, stdout читает судья.

STDOUT.sync = true                # сброс вывода после каждой строки, без него ход застрянет в буфере
n = gets.to_i                     # ← число итераций
move = "COOPERATE"
n.times do
  puts move                       # → ваш ход
  move = gets.strip               # ← ход соперника: в следующий раз ответить тем же
end
