#!/usr/bin/env lua
-- Аукцион двойной цены: стратегия «пас после порога».
-- Перебивать ставку соперника на 1, пока своя ставка не выше половины приза, дальше пас.
-- Протокол: ← строка от судьи (stdin), → ваша строка (stdout).
-- Здесь ходы поочерёдные: сначала приходит ставка соперника, потом ваш ответ.
-- Отладку печатайте в io.stderr, stdout читает судья.

local prize = tonumber(io.read("l"))   -- ← стоимость приза P
local rounds = tonumber(io.read("l"))  -- ← максимум раундов торгов
local limit = prize // 2               -- дороже половины приза не торговаться
for line in io.lines() do              -- ← ставка соперника (0 в начале торгов)
  local bid = tonumber(line) + 1       -- перебить на 1
  if bid > limit then
    bid = 0                            -- 0 = пас, торги заканчиваются
  end
  io.write(bid, "\n")                  -- → ставка: больше ставки соперника или 0
  io.stdout:flush()                    -- сброс вывода обязателен
end
