#!/usr/bin/env ruby
# Аукцион двойной цены: стратегия «пас после порога».
# Перебивать ставку соперника на 1, пока своя ставка не выше половины приза, дальше пас.
# Протокол: ← строка от судьи (stdin), → ваша строка (stdout).
# Здесь ходы поочерёдные: сначала приходит ставка соперника, потом ваш ответ.
# Отладку печатайте через warn, stdout читает судья.

STDOUT.sync = true                # сброс вывода после каждой строки, без него ход застрянет в буфере
prize = gets.to_i                 # ← стоимость приза P
rounds = gets.to_i                # ← максимум раундов торгов
limit = prize / 2                 # дороже половины приза не торговаться
while (line = gets)               # ← ставка соперника (0 в начале торгов); ввод кончается вместе с торгами
  bid = line.to_i + 1             # перебить на 1
  bid = 0 if bid > limit          # 0 = пас, торги заканчиваются
  puts bid                        # → ставка: больше ставки соперника или 0
end
