const STATUSES = [
  ['tournament', 'pending', 'команды собираются, загрузки ещё нет'],
  ['tournament', 'active', 'загрузка открыта, идут раунды'],
  ['tournament', 'completed', 'итог зафиксирован'],
  ['program', 'compiling', 'сборка в песочнице'],
  ['program', 'ready', 'будет играть в раундах'],
  ['program', 'failed', 'текст ошибки — на странице игры'],
  ['match', 'pending', 'ждёт свободного исполнителя'],
  ['match', 'running', 'программы играют'],
  ['match', 'completed', 'очки засчитаны'],
  ['match', 'failed', 'одна из программ ошиблась: 0 очков обеим, победа сопернику'],
  ['match', 'cancelled', 'турнир завершён или команда снята, матч не считается'],
] as const;

// Справка: единые термины, статусы, как считается место и частые вопросы.
// Ссылки из таблиц ведут на разделы по якорю (/help#place).
export function Help() {
  const { hash } = useLocation();
  useEffect(() => {
    if (hash) revealAndFocus(document.getElementById(decodeURIComponent(hash.slice(1))));
  }, [hash]);

  return (
    <div className="max-w-3xl">
      <PageHeader
        crumbs={[{ label: 'справка' }]}
        title={
          <>
            <title>Справка — TJudge</title>
            Справка
          </>
        }
      >
        <nav aria-label="Разделы справки" className="flex flex-wrap gap-x-4 gap-y-1 font-mono text-sm">
          <a href="#terms" className="text-primary-400 hover:underline">термины</a>
          <a href="#statuses" className="text-primary-400 hover:underline">статусы</a>
          <a href="#place" className="text-primary-400 hover:underline">как считается место</a>
          <a href="#faq" className="text-primary-400 hover:underline">вопросы</a>
        </nav>
      </PageHeader>

      <div className="card md">
        <h2 id="terms">Термины</h2>
        <p>От малого к большому: итерации складываются в матч, матчи — в раунд, раунды всех игр — в турнир.</p>
        {/* список, а не таблица: на телефоне термин встаёт над описанием */}
        <dl className="border-t border-line">
          {TERMS.map(([term, meaning]) => (
            <div key={term} className="border-b border-line py-2 sm:grid sm:grid-cols-[13rem_1fr] sm:gap-4">
              <dt className="font-mono font-semibold text-gray-100">{term}</dt>
              <dd>{meaning}</dd>
            </div>
          ))}
        </dl>

        <h2 id="statuses">Статусы</h2>
        <ScrollX as="div" label="Статусы, прокрутка по горизонтали">
          <table>
            <tbody>
              {STATUSES.map(([entity, status, meaning]) => (
                <tr key={`${entity}-${status}`}>
                  <td className="whitespace-nowrap">
                    <StatusLabel entity={entity} status={status} />
                  </td>
                  <td>
                    {entity === 'tournament' ? 'турнир' : entity === 'program' ? 'программа' : 'матч'}: {meaning}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </ScrollX>

        <h2 id="place">Как считается место</h2>
        <ul>
          <li>
            В таблице игры место — по сумме очков команды в сыгранных матчах текущего раунда этой игры. При равных очках выше та, у
            кого больше побед; при равных очках и победах место общее, а выше в списке та, чья играющая версия загружена раньше.
            Команда без сыгранных матчей игры стоит после всех сыгравших.
          </li>
          <li>
            В общей таблице турнира складываются места команды во всех играх турнира: чем меньше сумма мест, тем выше. Три первых
            места (1 + 1 + 1 = 3) выше трёх вторых (2 + 2 + 2 = 6), а 9 + 1 + 1 = 11 ниже обоих. Масштаб очков игры поэтому не
            важен: в одной игре очков сотни тысяч, в другой десятки, но каждая даёт в сумму только место. Команда, которая не
            сыграла игру, получает в ней место после последнего. При равной сумме мест выше та, у кого больше сумма очков всех
            игр; при равных сумме мест и очках место общее, выше в списке та, чья играющая версия загружена раньше.
          </li>
          <li>Новый раунд игры заменяет результаты прошлого: очки между раундами не копятся.</li>
          <li>
            Пока идёт раунд, места в играх и их сумма в общей таблице считаются по последним доигранным итогам игр. У идущей игры это итог её
            прошлого раунда, который был на экране до старта. Новые очки видны рядом с пометкой «◐ предварительно» и счётчиком
            сыгранных матчей, но место не меняют: частичная сумма зависит от того, чьи матчи очередь сыграла раньше, и давала бы
            ложные смены лидера. Когда игра доиграна, её новые очки заменяют прошлые, а стрелки ▲▼ рядом с местом показывают сдвиг.
            Повтор упавших матчей место не трогает.
          </li>
          <li>
            Если прошлого итога у идущей игры нет (первый раунд или страница открыта уже во время раунда), место в ней
            предварительное: по очкам за сыгранный матч, а не по сумме, потому что у команд к этому моменту сыграно разное число
            матчей. Такое место может меняться, пока игра не доиграна.
          </li>
          <li>
            Сыгранными считаются завершённые матчи и поражения по ошибке. В матче с ошибкой обе стороны получают 0 очков, а сопернику
            засчитывается победа. Отменённые матчи не считаются.
          </li>
        </ul>
        <p>
          <strong>Число побед место в игре не решает.</strong> Стратегия, которая почти не выигрывает матчи, но в каждом набирает много
          очков, окажется выше той, что часто побеждает с малым счётом. Классический пример — «око за око» в турнире Аксельрода: ни
          одного выигранного матча и первое место по сумме очков.
        </p>

        <h2 id="faq">Частые вопросы</h2>
        <h3>С чего начать?</h3>
        <p>
          <Link to="/games">Откройте игру</Link>: в блоке <code>$ начать</code> есть шаблон программы на десяти языках. Его можно
          скачать и загрузить в турнир как есть, а потом менять стратегию. Как программа
          обменивается строками с судьёй, объясняет «Анатомия хода» в <Link to="/games">правилах любой игры</Link>.
        </p>
        <h3>Почему программа проигрывает по таймауту?</h3>
        <p>
          Чаще всего ход застрял в буфере вывода: после каждой строки нужен сброс (flush). Как это сделать на вашем языке — в
          «Анатомии хода» в <Link to="/games">правилах любой игры</Link>. Ещё одна причина — ответ дольше 200 мс.
        </p>
        <h3>Программа собрана, но матчи падают. Где смотреть?</h3>
        <p>
          На странице игры, во вкладке «Матчи» с фильтром по ошибкам: там вердикт по-русски и хвост stderr вашей программы.
          Отладочный вывод печатайте в stderr, stdout читает судья.
        </p>
        <h3>Когда начнёт играть новая версия?</h3>
        <p>Со следующего раунда, если она собралась. Пока новая версия собирается или не собралась, играет прежняя.</p>
        <h3>Где взять код приглашения?</h3>
        <p>
          У капитана команды: страница команды → «Пригласить участников». Код турнира для вступления не подходит. Без кода можно
          вступить кнопкой «Вступить» у команды во вкладке «Команды» или в окне «Участвовать».
        </p>
      </div>
    </div>
  );
}
