#!/usr/bin/env php
<?php
// Общественное благо: стратегия «условный вклад».
// Сначала вложить всё, дальше столько же, сколько соперник вложил в прошлый раз.
// Протокол: ← строка от судьи (stdin), → ваша строка (stdout).
// Отладку печатайте в STDERR: fwrite(STDERR, ...), stdout читает судья.

$capital = (int) fgets(STDIN);        // ← капитал на итерацию E
$multiplier = (float) fgets(STDIN);   // ← множитель пула m, дробное число
$n = (int) fgets(STDIN);              // ← число итераций
$give = $capital;                     // первый вклад - весь капитал
for ($i = 0; $i < $n; $i++) {
    echo $give, "\n";                 // → вклад: целое число от 0 до E
    flush();                          // сброс вывода
    $give = (int) fgets(STDIN);       // ← вклад соперника: в следующий раз вложить столько же
}
