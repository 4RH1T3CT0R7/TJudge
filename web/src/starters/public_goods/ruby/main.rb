#!/usr/bin/env ruby
# Общественное благо: стратегия «условный вклад».
# Сначала вложить всё, дальше столько же, сколько соперник вложил в прошлый раз.
# Протокол: ← строка от судьи (stdin), → ваша строка (stdout).
# Отладку печатайте через warn, stdout читает судья.

STDOUT.sync = true                # сброс вывода после каждой строки, без него ход застрянет в буфере
capital = gets.to_i               # ← капитал на итерацию E
multiplier = gets.to_f            # ← множитель пула m, дробное число
n = gets.to_i                     # ← число итераций
give = capital                    # первый вклад - весь капитал
n.times do
  puts give                       # → вклад: целое число от 0 до E
  give = gets.to_i                # ← вклад соперника: в следующий раз вложить столько же
end
