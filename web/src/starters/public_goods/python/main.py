#!/usr/bin/env python3
# Общественное благо: стратегия «условный вклад».
# Сначала вложить всё, дальше столько же, сколько соперник вложил в прошлый раз.
# Протокол: ← строка от судьи (stdin), → ваша строка (stdout).
# Отладку печатайте в stderr: print(..., file=sys.stderr), stdout читает судья.

capital = int(input())            # ← капитал на итерацию E
multiplier = float(input())       # ← множитель пула m, дробное число
n = int(input())                  # ← число итераций
give = capital                    # первый вклад - весь капитал
for _ in range(n):
    print(give, flush=True)       # → вклад: целое число от 0 до E; flush=True обязателен
    give = int(input())           # ← вклад соперника: в следующий раз вложить столько же
