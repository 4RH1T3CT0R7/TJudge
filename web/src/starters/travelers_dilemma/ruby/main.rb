#!/usr/bin/env ruby
# Дилемма путешественника: стратегия «заявка 90».
# Каждую итерацию одна и та же высокая заявка, но внутри границ [L, U].
# Протокол: ← строка от судьи (stdin), → ваша строка (stdout).
# Отладку печатайте через warn, stdout читает судья.

STDOUT.sync = true                # сброс вывода после каждой строки
low = gets.to_i                   # ← нижняя граница L
high = gets.to_i                  # ← верхняя граница U
bonus = gets.to_i                 # ← бонус и штраф R
n = gets.to_i                     # ← число итераций
claim = 90.clamp(low, high)       # 90, если оно внутри [L, U]
n.times do
  puts claim                      # → заявка: целое число от L до U
  opponent = gets.to_i            # ← заявка соперника
end
