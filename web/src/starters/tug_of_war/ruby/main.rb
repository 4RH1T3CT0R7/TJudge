#!/usr/bin/env ruby
# Перетягивание каната: стратегия «равная трата».
# Остаток энергии делится поровну на оставшиеся итерации, к концу тратится весь.
# Протокол: ← строка от судьи (stdin), → ваша строка (stdout).
# Отладку печатайте через warn, stdout читает судья.

STDOUT.sync = true                # сброс вывода после каждой строки
energy = gets.to_i                # ← начальная энергия
n = gets.to_i                     # ← число итераций
n.times do |i|
  spend = energy / (n - i)        # поровну на оставшиеся итерации
  energy -= spend
  puts spend                      # → трата: от 0 до остатка
  opponent = gets.to_i            # ← трата соперника
end
