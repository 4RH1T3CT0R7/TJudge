#!/usr/bin/env php
<?php
// Перетягивание каната: стратегия «равная трата».
// Остаток энергии делится поровну на оставшиеся итерации, к концу тратится весь.
// Протокол: ← строка от судьи (stdin), → ваша строка (stdout).
// Отладку печатайте в STDERR: fwrite(STDERR, ...), stdout читает судья.

$energy = (int) fgets(STDIN);         // ← начальная энергия
$n = (int) fgets(STDIN);              // ← число итераций
for ($i = 0; $i < $n; $i++) {
    $spend = intdiv($energy, $n - $i);  // поровну на оставшиеся итерации
    $energy -= $spend;
    echo $spend, "\n";                // → сколько потратить: от 0 до остатка
    flush();                          // сброс вывода
    $opponent = (int) fgets(STDIN);   // ← сколько потратил соперник
}
