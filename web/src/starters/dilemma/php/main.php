#!/usr/bin/env php
<?php
// Дилемма заключённого: стратегия «око за око» (tit for tat).
// Первый ход - сотрудничество, дальше повтор прошлого хода соперника.
// Протокол: ← строка от судьи (stdin), → ваша строка (stdout).
// Отладку печатайте в STDERR: fwrite(STDERR, ...), stdout читает судья.

$n = (int) fgets(STDIN);          // ← число итераций
$move = "COOPERATE";
for ($i = 0; $i < $n; $i++) {
    echo $move, "\n";             // → ваш ход
    flush();                      // сброс вывода
    $move = trim(fgets(STDIN));   // ← ход соперника: в следующий раз ответить тем же
}
