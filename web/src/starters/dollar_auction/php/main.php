#!/usr/bin/env php
<?php
// Аукцион двойной цены: стратегия «пас после порога».
// Перебивать соперника на 1, пока ставка не выше половины приза, дальше пас.
// Протокол: ← строка от судьи (stdin), → ваша строка (stdout).
// Ходы поочерёдные: сначала ставка соперника, потом ваш ответ. О пасе соперника
// судья не сообщает: ввод просто заканчивается.
// Отладку печатайте в STDERR: fwrite(STDERR, ...), stdout читает судья.

$prize = (int) fgets(STDIN);                    // ← приз P
$maxIters = (int) fgets(STDIN);                 // ← максимум итераций
$limit = intdiv($prize, 2);                     // дороже половины приза не торговаться
while (($line = fgets(STDIN)) !== false) {      // ← ставка соперника, 0 в начале торгов
    $bid = (int) $line + 1;                     // перебить на 1
    if ($bid > $limit) {
        $bid = 0;                               // 0 = пас, торги заканчиваются
    }
    echo $bid, "\n";                            // → ставка выше соперника или 0
    flush();                                    // сброс вывода
}
