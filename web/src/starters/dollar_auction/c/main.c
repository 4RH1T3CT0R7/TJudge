// Аукцион двойной цены: стратегия «пас после порога».
// Перебивать ставку соперника на 1, пока своя ставка не выше половины приза, дальше пас.
// Протокол: ← строка от судьи (stdin), → ваша строка (stdout).
// Здесь ходы поочерёдные: сначала приходит ставка соперника, потом ваш ответ.
// Отладку печатайте в stderr: fprintf(stderr, ...), stdout читает судья.
#include <stdio.h>

int main(void) {
    int prize, rounds, opponent;
    if (scanf("%d %d", &prize, &rounds) != 2) return 1;  // ← стоимость приза P и максимум раундов торгов
    int limit = prize / 2;                             // дороже половины приза не торговаться
    while (scanf("%d", &opponent) == 1) {              // ← ставка соперника (0 в начале торгов)
        int bid = opponent + 1;                        // перебить на 1
        if (bid > limit) bid = 0;                      // 0 = пас, торги заканчиваются
        printf("%d\n", bid);                           // → ставка: больше ставки соперника или 0
        fflush(stdout);                                // сброс вывода обязателен
    }
    return 0;
}
