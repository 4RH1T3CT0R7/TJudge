#!/usr/bin/env python3
# Аукцион двойной цены: стратегия «пас после порога».
# Перебивать ставку соперника на 1, пока своя ставка не выше половины приза, дальше пас.
# Протокол: ← строка от судьи (stdin), → ваша строка (stdout).
# Здесь ходы поочерёдные: сначала приходит ставка соперника, потом ваш ответ.
# Отладку печатайте в stderr: print(..., file=sys.stderr), stdout читает судья.
import sys

prize = int(input())              # ← стоимость приза P
rounds = int(input())             # ← максимум раундов торгов
limit = prize // 2                # дороже половины приза не торговаться
for line in sys.stdin:            # ← ставка соперника (0 в начале торгов); ввод кончается вместе с торгами
    bid = int(line) + 1           # перебить на 1
    if bid > limit:
        bid = 0                   # 0 = пас, торги заканчиваются
    print(bid, flush=True)        # → ставка: больше ставки соперника или 0; flush=True обязателен
